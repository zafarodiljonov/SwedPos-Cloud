"""
Builds locale/uz and locale/ru django.po from the desktop app's texts (src/SwedPos.App/Loc.cs) plus the website's
own texts below, so the website uses exactly the desktop's wording. Message ids are the desktop keys ("an_revenue").

    python tools/make_texts.py ../src/SwedPos.App/Loc.cs
    python tools/compile_messages.py
"""
import re
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent

WEB_TEXTS = {
    "web_title": ("SwedPos Cloud", "SwedPos Cloud"),
    "web_tagline": ("Restoraningiz savdosi va hisobotlari — istalgan joydan.", "Продажи и отчёты вашего ресторана — из любого места."),
    "web_login_title": ("Kirish", "Вход"),
    "web_phone": ("Telefon raqami", "Номер телефона"),
    "web_password": ("Parol", "Пароль"),
    "web_login": ("Kirish", "Войти"),
    "web_logout": ("Chiqish", "Выйти"),
    "web_bad_login": ("Telefon raqami yoki parol noto'g'ri.", "Неверный номер телефона или пароль."),
    "web_no_restaurants": ("Bu hisobga hali restoran biriktirilmagan. SwedPos bilan bog'laning.", "К этому аккаунту ещё не привязан ресторан. Свяжитесь с SwedPos."),
    "web_last_sync": ("Oxirgi ma'lumot", "Последние данные"),
    "web_never_synced": ("Restorandan hali ma'lumot kelmagan", "Данные из ресторана ещё не поступали"),
    "web_live_note": ("Ma'lumotlar restoran server kompyuteridan har daqiqada keladi.", "Данные приходят с серверного компьютера ресторана каждую минуту."),
    "web_secure": ("Ulanish himoyalangan. PIN-kodlar saytga yuborilmaydi.", "Соединение защищено. PIN-коды на сайт не передаются."),
    "web_month_prev": ("Oldingi oy", "Предыдущий месяц"),
    "web_month_next": ("Keyingi oy", "Следующий месяц"),
    "web_apply": ("Ko'rsatish", "Показать"),
    "web_admin": ("Boshqaruv", "Управление"),
    "web_close": ("Yopish", "Закрыть"),
}

PAIR = re.compile(r'\["([A-Za-z0-9_]+)"\]\s*=\s*\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)')


def cs_unescape(s: str) -> str:
    return s.replace('\\"', '"').replace("\\\\", "\\")


def po_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main(loc_path: str):
    texts = {}
    for key, uz, ru in PAIR.findall(Path(loc_path).read_text(encoding="utf-8")):
        texts.setdefault(key, (cs_unescape(uz), cs_unescape(ru)))
    texts.update(WEB_TEXTS)
    for index, lang in enumerate(("uz", "ru")):
        out = BASE_DIR / "locale" / lang / "LC_MESSAGES" / "django.po"
        out.parent.mkdir(parents=True, exist_ok=True)
        lines = [
            "# Generated by tools/make_texts.py from the desktop app's Loc.cs. Do not edit by hand.",
            'msgid ""',
            'msgstr ""',
            '"Content-Type: text/plain; charset=UTF-8\\n"',
            f'"Language: {lang}\\n"',
            "",
        ]
        for key in sorted(texts):
            lines += [f'msgid "{po_escape(key)}"', f'msgstr "{po_escape(texts[key][index])}"', ""]
        out.write_text("\n".join(lines), encoding="utf-8")
        print(f"{out.relative_to(BASE_DIR)}: {len(texts)} texts")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(BASE_DIR.parent / "src" / "SwedPos.App" / "Loc.cs"))
